'use server';
/* The store's help window (2026-10-12): automated answers from fixed help topics, a message to the team (a support
   ticket), and order status for someone who is not signed in. Nothing here is generated by a model, and nothing claims
   to be a person: the answers are the topics in core (helpTopics), matched by keywords.
   Every action is limited per address; the order lookup also per order number, and a guest's message also per email.
   The lookup answers a wrong order number and a wrong contact with the same sentence.
   Where no rate limiter is configured on a production deployment, the order lookup and a guest's message are closed HERE,
   on the server (lib/guest-help.ts): a request sent straight to these actions is refused whatever the page showed. */
import { DomainError } from '@kitsyuu/contracts';
import { guestOrderStatus, helpTopics, lookupContact, matchHelpTopics, openCustomerTicket, openGuestTicket, type GuestOrderStatus } from '@kitsyuu/core';
import { GUEST_LOOKUP_CLOSED, GUEST_MESSAGE_CLOSED } from '@/lib/guest-help';
import { guestHelpAllowed, limited, limitedByAddress } from '@/lib/rate-limit';
import { currentCustomer, db, requestContext } from '@/lib/server';

const text = (v: FormDataEntryValue | null, max: number) => (typeof v === 'string' ? v.trim().slice(0, max) : '');
const NOT_FOUND = 'We could not find an order with that number and contact. Check both and try again, or send us a message.';

export async function askHelpAction(question: string): Promise<{ ok: boolean; message?: string; topics: { id: string; question: string; answer: string }[] }> {
  const wait = await limitedByAddress('help-ask');
  if (wait) return { ok: false, message: wait, topics: [] };
  try {
    const found = matchHelpTopics(await helpTopics(db()), String(question ?? '').slice(0, 300));
    return { ok: true, topics: found.map(t => ({ id: t.id, question: t.question, answer: t.answer })) };
  } catch (e) {
    console.error('[help] ask', (e as Error).message);
    return { ok: false, message: 'Help topics are not available right now.', topics: [] };
  }
}

export async function orderStatusAction(form: FormData): Promise<{ ok: boolean; message?: string; order?: Extract<GuestOrderStatus, { found: true }> }> {
  if (!guestHelpAllowed()) return { ok: false, message: GUEST_LOOKUP_CLOSED };   // before anything is read or looked up
  const orderNumber = text(form.get('orderNumber'), 40).toUpperCase(), contact = text(form.get('contact'), 254);
  if (!orderNumber) return { ok: false, message: 'Enter your order number.' };
  if (!lookupContact(contact)) return { ok: false, message: 'Enter the email address or the 10-digit phone number you ordered with.' };
  // Per address (someone trying many orders) and per order number (many addresses trying one order's contact).
  const wait = (await limitedByAddress('order-lookup')) ?? (await limited('order-lookup-order', orderNumber));
  if (wait) return { ok: false, message: wait };
  try {
    const r = await guestOrderStatus(db(), { orderNumber, contact });
    return r.found ? { ok: true, order: r } : { ok: false, message: NOT_FOUND };
  } catch (e) {
    console.error('[help] order status', (e as Error).message);
    return { ok: false, message: 'Order status is not available right now. Please try again later.' };
  }
}

export async function sendHelpMessageAction(form: FormData): Promise<{ ok: boolean; message: string; ticket?: string }> {
  // A field people never see or fill; a form that fills it is answered as if it had worked and nothing is stored.
  if (text(form.get('website'), 200)) return { ok: true, message: 'Thank you. Your message has been sent.' };
  const input = { categoryCode: text(form.get('categoryCode'), 40), subject: text(form.get('subject'), 160), body: text(form.get('body'), 3800), orderNumber: text(form.get('orderNumber'), 40).toUpperCase() || null };
  if (!input.categoryCode) return { ok: false, message: 'Choose a topic.' };
  if (!input.subject) return { ok: false, message: 'Say what this is about.' };
  if (!input.body) return { ok: false, message: 'Write your message.' };
  try {
    const me = await currentCustomer();
    if (me) {
      const wait = await limited('ticket-open', me.customerId);
      if (wait) return { ok: false, message: wait };
      const t = await openCustomerTicket(db(), me, input, await requestContext());
      return { ok: true, ticket: t.number, message: `Your message has been sent (ticket ${t.number}). We reply by email, and you can follow it under My account → Support.` };
    }
    if (!guestHelpAllowed()) return { ok: false, message: GUEST_MESSAGE_CLOSED };   // a signed-in customer never reaches this line
    const name = text(form.get('name'), 120), email = text(form.get('email'), 254).toLowerCase();
    if (!name) return { ok: false, message: 'Enter your name.' };
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) return { ok: false, message: 'Enter a valid email address.' };
    const wait = (await limitedByAddress('guest-ticket')) ?? (await limited('guest-ticket-email', email));
    if (wait) return { ok: false, message: wait };
    const t = await openGuestTicket(db(), { ...input, name, email }, await requestContext());
    return { ok: true, ticket: t.number, message: `Your message has been sent (ticket ${t.number}). We reply by email to ${email}.` };
  } catch (e) {
    if (e instanceof DomainError) return { ok: false, message: e.message };
    console.error('[help] message', (e as Error).message);
    return { ok: false, message: 'Your message could not be sent right now. Nothing was saved; please try again.' };
  }
}
